#!/usr/bin/env node

const fs = require('fs')
const path = require('path')
const { spawnSync } = require('child_process')

const REPO_ROOT = path.resolve(__dirname, '..')

async function loadPathContracts() {
  return import('../skill/lib/contracts/paths.js')
}

// APP_EXCLUSION_RULES drives copyArtifactFiles' filter for the app/
// tree. Each rule is an object literal so the smoke test can walk the
// list and assert every rule fires. The previous implementation was a
// chained boolean expression; that form does not let the smoke test
// introspect what gets excluded.
//
// Each rule fires against a POSIX relative path under app/.
// The rule's `reason` is for humans reading smoke-test failures.
function createAppExclusionRules(paths) {
  return [
    {
      name: 'node_modules',
      reason: 'Installed dependencies are rebuilt at install time.',
      matches(relativePath) {
        return relativePath === 'node_modules' || relativePath.startsWith('node_modules/')
      },
    },
    {
      name: 'dist',
      reason: 'Build output is regenerated by the artifact consumer.',
      matches(relativePath) {
        return relativePath === 'dist' || relativePath.startsWith('dist/')
      },
    },
    {
      name: 'maps-manifest',
      reason: 'The maps manifest is written fresh by writeRuntimePlaceholders.',
      matches(relativePath) {
        return relativePath === `public/${paths.MAPS_MANIFEST_FILENAME}`
      },
    },
    {
      name: 'legacy-runtime-graphs',
      reason: 'Legacy runtime graph/state files at app/public root; graphs now live under public/graph/.',
      matches(relativePath) {
        return /^public\/claudemap-runtime(-state)?(\.[^/]+)?\.json$/.test(relativePath)
      },
    },
    {
      name: 'graph-directory',
      reason: 'Current-state runtime graphs are written fresh by writeRuntimePlaceholders.',
      matches(relativePath) {
        return (
          relativePath === `public/${paths.GRAPH_DIR_NAME}` ||
          relativePath.startsWith(`public/${paths.GRAPH_DIR_NAME}/`)
        )
      },
    },
  ]
}

function printUsage() {
  console.log('ClaudeMap skill packager')
  console.log('  node scripts/package-claudemap-skill.js [--output <dir>] [--zip]')
}

function parseArgs(argv, defaultOutputRoot) {
  const options = {
    outputRoot: defaultOutputRoot,
    zip: false,
  }

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]

    if (argument === '--help' || argument === '-h') {
      options.help = true
      continue
    }

    if (argument === '--zip') {
      options.zip = true
      continue
    }

    if (argument === '--output') {
      const nextValue = argv[index + 1]

      if (!nextValue) {
        throw new Error('Missing value for --output')
      }

      options.outputRoot = path.resolve(nextValue)
      index += 1
      continue
    }

    throw new Error(`Unknown argument: ${argument}`)
  }

  return options
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/')
}

function copyFile(relativeSourcePath, artifactRoot, relativeTargetPath = relativeSourcePath) {
  const sourcePath = path.join(REPO_ROOT, relativeSourcePath)
  const targetPath = path.join(artifactRoot, relativeTargetPath)

  fs.mkdirSync(path.dirname(targetPath), { recursive: true })
  fs.copyFileSync(sourcePath, targetPath)
}

function writeJsonFile(filePath, data) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2))
}

function createEmptyRuntimeGraph(contracts) {
  return {
    meta: {
      repoName: 'claudemap',
      branch: 'workspace',
      creditLabel: 'ClaudeMap skill',
      generatedAt: null,
      source: contracts.GRAPH_SOURCES.FILE_SHIM,
    },
    nodes: [],
    edges: [],
    files: [],
  }
}

function createDefaultMapsManifest(paths) {
  return {
    version: 1,
    activeMapId: 'root',
    maps: [
      {
        id: 'root',
        label: 'ClaudeMap',
        summary: 'Full repo overview',
        scope: null,
        cachePath: paths.CACHE_FILENAME,
        graphPath: paths.RUNTIME_GRAPH_REL,
        statePath: paths.RUNTIME_STATE_REL,
      },
    ],
  }
}

function createDefaultRuntimeStateFromGraph(graphData, contracts) {
  const { GRAPH_SOURCES, PRESENTATION_MODES } = contracts
  const normalizedGraph = graphData && Array.isArray(graphData.nodes) && Array.isArray(graphData.edges)
    ? graphData
    : createEmptyRuntimeGraph(contracts)

  return {
    graphRevision: 0,
    updatedAt: normalizedGraph.meta?.generatedAt || null,
    graphMeta: {
      repoName: normalizedGraph.meta?.repoName || 'claudemap',
      generatedAt: normalizedGraph.meta?.generatedAt || null,
      source: normalizedGraph.meta?.source || GRAPH_SOURCES.SEED,
      nodeCount: normalizedGraph.nodes.length,
      edgeCount: normalizedGraph.edges.length,
      fileCount: Array.isArray(normalizedGraph.files) ? normalizedGraph.files.length : 0,
    },
    runtime: {
      healthOverlay: false,
      highlightedNodeIds: [],
      highlightColor: 'accent',
      focus: null,
      guidedFlow: null,
      presentation: {
        mode: PRESENTATION_MODES.FREE,
        lockInput: false,
        title: null,
        explanation: null,
        body: null,
        stepLabel: null,
        updatedAt: null,
      },
    },
  }
}

function readJsonFileOrFallback(filePath, fallbackFactory) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'))
  } catch {
    return fallbackFactory()
  }
}

function writeRuntimePlaceholders(projectRoot, contracts, paths, skillRoot, graphSourcePath) {
  const packagedGraph = readJsonFileOrFallback(
    graphSourcePath,
    () => createEmptyRuntimeGraph(contracts),
  )

  // Graphs live in a dedicated `graph/` subdirectory under `app/public/` so
  // runtime graph outputs have an obvious home and are not mixed with
  // unrelated static assets.
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.RUNTIME_GRAPH_REL),
    packagedGraph,
  )
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.RUNTIME_STATE_REL),
    createDefaultRuntimeStateFromGraph(packagedGraph, contracts),
  )
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.MAPS_MANIFEST_FILENAME),
    createDefaultMapsManifest(paths),
  )
}

async function loadContracts() {
  const [{ GRAPH_SOURCES }, { PRESENTATION_MODES }] = await Promise.all([
    import('../skill/lib/contracts/graph-sources.js'),
    import('../skill/lib/contracts/presentation.js'),
  ])
  return { GRAPH_SOURCES, PRESENTATION_MODES }
}

function writeTextFile(filePath, content) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, content)
}

async function loadCommandDescriptors() {
  const [
    setup,
    update,
    open,
    create,
    show,
    snapshot,
    slashOnly,
  ] = await Promise.all([
    import('../skill/commands/setup-claudemap.js'),
    import('../skill/commands/refresh.js'),
    import('../skill/commands/open-claudemap.js'),
    import('../skill/commands/create-map.js'),
    import('../skill/commands/show.js'),
    import('../skill/commands/snapshot.js'),
    import('../skill/lib/command-harness/slash-only-descriptors.js'),
  ])

  return [
    setup.SETUP_CLAUDEMAP_COMMAND,
    update.UPDATE_COMMAND,
    open.OPEN_CLAUDEMAP_COMMAND,
    create.CREATE_MAP_COMMAND,
    show.SHOW_COMMAND,
    snapshot.SNAPSHOT_COMMAND,
    slashOnly.EXPLAIN_SLASH_COMMAND,
  ]
}

async function createSlashCommandTemplates() {
  const { renderSlashTemplate, slashFileName } = await import('../skill/lib/command-harness/render-slash-template.js')
  const descriptors = await loadCommandDescriptors()
  const templates = {}

  for (const descriptor of descriptors) {
    if (descriptor.noSlashTemplate) continue
    templates[slashFileName(descriptor)] = renderSlashTemplate(descriptor)
  }

  return templates
}

async function writeSlashCommands(artifactRoot, commandsRoot) {
  const commandTemplates = await createSlashCommandTemplates()

  for (const [fileName, content] of Object.entries(commandTemplates)) {
    writeTextFile(path.join(artifactRoot, commandsRoot, fileName), content)
  }
}


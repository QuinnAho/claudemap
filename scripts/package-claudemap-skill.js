function parseArgs(argv, defaultOutputRoot) {
  const options = {
    outputRoot: defaultOutputRoot,
    zip: false,
    assistant: 'claude',
  }

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index]

    if (argument === '--help' || argument === '-h') {
      options.help = true
      continue
    }

    if (argument === '--zip') {
      options.zip = true
      continue
    }

    if (argument === '--output') {
      const nextValue = argv[index + 1]

      if (!nextValue) {
        throw new Error('Missing value for --output')
      }

      options.outputRoot = path.resolve(nextValue)
      index += 1
      continue
    }

    if (argument === '--assistant') {
      const nextValue = argv[index + 1]

      if (!nextValue) {
        throw new Error('Missing value for --assistant')
      }

      if (!['claude', 'codex', 'all'].includes(nextValue)) {
        throw new Error(`Invalid --assistant value: ${nextValue}. Valid: claude, codex, all`)
      }

      options.assistant = nextValue
      index += 1
      continue
    }

    throw new Error(`Unknown argument: ${argument}`)
  }

  return options
}

function toPosix(relativePath) {
  return relativePath.split(path.sep).join('/')
}

function copyFile(relativeSourcePath, artifactRoot, relativeTargetPath = relativeSourcePath) {
  const sourcePath = path.join(REPO_ROOT, relativeSourcePath)
  const targetPath = path.join(artifactRoot, relativeTargetPath)

  fs.mkdirSync(path.dirname(targetPath), { recursive: true })
  fs.copyFileSync(sourcePath, targetPath)
}

function writeJsonFile(filePath, data) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true })
  fs.writeFileSync(filePath, JSON.stringify(data, null, 2))
}

function createEmptyRuntimeGraph(contracts) {
  return {
    meta: {
      repoName: 'claudemap',
      branch: 'workspace',
      creditLabel: 'ClaudeMap skill',
      generatedAt: null,
      source: contracts.GRAPH_SOURCES.FILE_SHIM,
    },
    nodes: [],
    edges: [],
    files: [],
  }
}

function createDefaultMapsManifest(paths) {
  return {
    version: 1,
    activeMapId: 'root',
    maps: [
      {
        id: 'root',
        label: 'ClaudeMap',
        summary: 'Full repo overview',
        scope: null,
        cachePath: paths.CACHE_FILENAME,
        graphPath: paths.RUNTIME_GRAPH_REL,
        statePath: paths.RUNTIME_STATE_REL,
      },
    ],
  }
}

function createDefaultRuntimeStateFromGraph(graphData, contracts) {
  const { GRAPH_SOURCES, PRESENTATION_MODES } = contracts
  const normalizedGraph = graphData && Array.isArray(graphData.nodes) && Array.isArray(graphData.edges)
    ? graphData
    : createEmptyRuntimeGraph(contracts)

  return {
    graphRevision: 0,
    updatedAt: normalizedGraph.meta?.generatedAt || null,
    graphMeta: {
      repoName: normalizedGraph.meta?.repoName || 'claudemap',
      generatedAt: normalizedGraph.meta?.generatedAt || null,
      source: normalizedGraph.meta?.source || GRAPH_SOURCES.SEED,
      nodeCount: normalizedGraph.nodes.length,
      edgeCount: normalizedGraph.edges.length,
      fileCount: Array.isArray(normalizedGraph.files) ? normalizedGraph.files.length : 0,
    },
    runtime: {
      healthOverlay: false,
      highlightedNodeIds: [],
      highlightColor: 'accent',
      focus: null,
      guidedFlow: null,
      presentation: {
        mode: PRESENTATION_MODES.FREE,
        lockInput: false,
        title: null,
        explanation: null,
        body: null,
        stepLabel: null,
        updatedAt: null,
      },
    },
  }
}

function readJsonFileOrFallback(filePath, fallbackFactory) {
  try {
    return JSON.parse(fs.readFileSync(filePath, 'utf8'))
  } catch {
    return fallbackFactory()
  }
}

function writeRuntimePlaceholders(projectRoot, contracts, paths, skillRoot, graphSourcePath) {
  const packagedGraph = readJsonFileOrFallback(
    graphSourcePath,
    () => createEmptyRuntimeGraph(contracts),
  )

  // Graphs live in a dedicated `graph/` subdirectory under `app/public/` so
  // runtime graph outputs have an obvious home and are not mixed with
  // unrelated static assets.
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.RUNTIME_GRAPH_REL),
    packagedGraph,
  )
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.RUNTIME_STATE_REL),
    createDefaultRuntimeStateFromGraph(packagedGraph, contracts),
  )
  writeJsonFile(
    path.join(projectRoot, skillRoot, 'app', 'public', paths.MAPS_MANIFEST_FILENAME),
    createDefaultMapsManifest(paths),
  )
}


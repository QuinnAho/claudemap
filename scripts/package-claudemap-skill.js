// APP_EXCLUSION_RULES drives copyArtifactFiles' filter for the app/
// tree. Each rule is an object literal so the smoke test can walk the
// list and assert every rule fires. The previous implementation was a
// chained boolean expression; that form does not let the smoke test
// introspect what gets excluded.
//
// Each rule fires against a POSIX relative path under app/.
// The rule's `reason` is for humans reading smoke-test failures.
function createAppExclusionRules(paths) {
  return [
    {
      name: 'node_modules',
      reason: 'Installed dependencies are rebuilt at install time.',
      matches(relativePath) {
        return relativePath === 'node_modules' || relativePath.startsWith('node_modules/')
      },
    },
    {
      name: 'dist',
      reason: 'Build output is regenerated by the artifact consumer.',
      matches(relativePath) {
        return relativePath === 'dist' || relativePath.startsWith('dist/')
      },
    },
    {
      name: 'maps-manifest',
      reason: 'The maps manifest is written fresh by writeRuntimePlaceholders.',
      matches(relativePath) {
        return relativePath === `public/${paths.MAPS_MANIFEST_FILENAME}`
      },
    },
    {
      name: 'legacy-runtime-graphs',
      reason: 'Legacy runtime graph/state files at app/public root; graphs now live under public/graph/.',
      matches(relativePath) {
        return /^public\/claudemap-runtime(-state)?(\.[^/]+)?\.json$/.test(relativePath)
      },
    },
    {
      name: 'graph-directory',
      reason: 'Current-state runtime graphs are written fresh by writeRuntimePlaceholders.',
      matches(relativePath) {
        return (
          relativePath === `public/${paths.GRAPH_DIR_NAME}` ||
          relativePath.startsWith(`public/${paths.GRAPH_DIR_NAME}/`)
        )
      },
    },
    {
      name: 'unit-test-files',
      reason: 'Test sources are development-only and must not ship with the packaged runtime.',
      matches(relativePath) {
        return isTestSourcePath(relativePath)
      },
    },
  ]
}

// Test-source matcher shared by the skill and app filters. We match
// both `*.test.js`/`*.test.jsx` (co-located unit tests) and any file
// under a `__tests__/` folder, which is the other convention the
// repo uses. `.mjs`/`.ts` variants are included for forward-compat
// in case a test is ever renamed; the current tree has none, but the
// packager should not be the reason a renamed test leaks.
function isTestSourcePath(relativePath) {
  if (/\.test\.(js|jsx|mjs|ts|tsx)$/.test(relativePath)) {
    return true
  }
  if (relativePath === '__tests__' || relativePath.startsWith('__tests__/') || relativePath.includes('/__tests__/')) {
    return true
  }
  return false
}

